/**
 * The judge chip's contract: Target vs Measured as numbers, the shared status
 * mark for the verdict (pass = done, fail = error, inconclusive = queued),
 * the judge's name, and evidence that expands on click. A rejected record
 * ({ok: false}) renders the honest error line.
 */

import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, it } from 'vitest'

// eslint-disable-next-line no-restricted-imports
import { registerPluginLocales } from '@/i18n/plugin-i18n'

import { AMBITION_LOCALES } from './i18n'
import { AmbitionJudgePart } from './judge'

const args = (over: Record<string, unknown> = {}) => ({
  card_id: 'card-e2e-ambition-1',
  evidence: 'checklist output: 12 of 12 notes generated by the outside tool',
  judge: 'outside checklist tool',
  measured: '12 notes',
  verdict: 'pass',
  ...over
})

const result = {
  card_id: 'card-e2e-ambition-1',
  ok: true,
  report_line: 'Target: 12 notes / Measured: 12 notes / Judge: pass (outside checklist tool)',
  target: '12 notes',
  verdict: 'pass'
}

const slot = (container: HTMLElement, name: string): HTMLElement | null =>
  container.querySelector(`[data-slot="${name}"]`)

beforeEach(() => {
  registerPluginLocales('ambition', AMBITION_LOCALES)
})

afterEach(() => {
  cleanup()
})

const mount = (props: { args?: Record<string, unknown>; isError?: boolean; result?: unknown } = {}) =>
  render(
    <AmbitionJudgePart
      args={props.args ?? args()}
      isError={props.isError ?? false}
      result={props.result ?? result}
      toolCallId="tc-2"
      toolName="ambition_judge"
    />
  )

describe('AmbitionJudgePart', () => {
  it('renders target vs measured as numbers with the verdict mark', async () => {
    const { container } = mount()

    expect(slot(container, 'ambition-judge')?.getAttribute('data-verdict')).toBe('pass')
    expect(slot(container, 'ambition-judge-target')?.textContent).toBe('Target: 12 notes')
    expect(slot(container, 'ambition-judge-measured')?.textContent).toBe('Measured: 12 notes')
    expect(screen.getByLabelText('Pass')).toBeTruthy()
    expect(container.textContent).toContain('outside checklist tool')
  })

  it('maps fail to the error mark and inconclusive to the muted one', () => {
    const failing = mount({ args: args({ verdict: 'fail' }), result: { ...result, verdict: 'fail' } })

    expect(slot(failing.container, 'ambition-judge')?.getAttribute('data-verdict')).toBe('fail')
    expect(screen.getByLabelText('Fail')).toBeTruthy()

    cleanup()

    const unclear = mount({
      args: args({ measured: 'no reading', verdict: 'inconclusive' }),
      result: { ...result, verdict: 'inconclusive' }
    })

    expect(slot(unclear.container, 'ambition-judge')?.getAttribute('data-verdict')).toBe('inconclusive')
    expect(screen.getByLabelText('Inconclusive')).toBeTruthy()
  })

  it('expands the evidence on click and hides it again', async () => {
    const { container } = mount()

    expect(slot(container, 'ambition-judge-evidence')).toBeNull()

    fireEvent.click(slot(container, 'ambition-judge-evidence-toggle') as HTMLElement)

    await waitFor(() =>
      expect(slot(container, 'ambition-judge-evidence')?.textContent).toContain('12 of 12 notes generated')
    )

    fireEvent.click(slot(container, 'ambition-judge-evidence-toggle') as HTMLElement)

    await waitFor(() => expect(slot(container, 'ambition-judge-evidence')).toBeNull())
  })

  it('renders the honest error line when the plugin rejected the record', () => {
    const { container } = mount({
      result: { error: 'the judge must be OUTSIDE this run', ok: false, reason: 'self_judge' }
    })

    expect(slot(container, 'ambition-judge-error')).toBeTruthy()
    expect(container.textContent).toContain('the judge must be OUTSIDE this run')
    expect(slot(container, 'ambition-judge')).toBeNull()
  })
})
