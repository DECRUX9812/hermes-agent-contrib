/**
 * The judge chip's contract, with the real api layer bound to a scripted
 * `ctx.rest`:
 *
 *  - Target vs Measured as numbers, the shared status mark for the verdict
 *    (pass = done, fail = error, inconclusive = queued), the judge's name, and
 *    evidence that expands on click;
 *  - the Target shown is the one the judge was handed, and when the card has
 *    moved it since, the chip says so and names the value the card carries now;
 *  - a rejected record ({ok: false}) renders the honest error line.
 */

import { QueryClient, QueryClientProvider } from '@tanstack/react-query'
import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'

// Test harness supplies the host's locale registration, as plugin loading does.
// eslint-disable-next-line no-restricted-imports
import { registerPluginLocales } from '@/i18n/plugin-i18n'
// eslint-disable-next-line no-restricted-imports
import { $selectedStoredSessionId } from '@/store/session'

import { type AmbitionRest, bindAmbitionApi } from './api'
import { AMBITION_LOCALES } from './i18n'
import { AmbitionJudgePart } from './judge'

const SESSION = '20260101_090000_abc123'
const CARD_ID = 'card-e2e-ambition-1'
const JUDGED_TARGET = '12 notes'

const args = (over: Record<string, unknown> = {}) => ({
  card_id: CARD_ID,
  evidence: 'checklist output: 12 of 12 notes generated by the outside tool',
  judge: 'outside checklist tool',
  measured: '12 notes',
  verdict: 'pass',
  ...over
})

const result = {
  card_id: CARD_ID,
  ok: true,
  report_line: 'Target: 12 notes / Measured: 12 notes / Judge: pass (outside checklist tool)',
  target: JUDGED_TARGET,
  verdict: 'pass'
}

/** The card as the backend carries it NOW — `target` is the field the user can
 *  still move after the verdict was recorded. */
const card = (target: string) => ({
  created_at: '2026-01-01T09:00:00Z',
  decided_at: null,
  edited_fields: null,
  fields: {
    altitude: 'Make the demo workspace self-checking after every batch run.',
    depth: 'Start from the sample queue fixtures.',
    judge: 'The outside checklist script.',
    range: 'Wire the checker into the batch runner.',
    target
  },
  id: CARD_ID,
  judge: null,
  session_id: SESSION,
  status: 'edited',
  updated_at: '2026-01-01T09:05:00Z',
  widens_scope: false
})

let rest: ReturnType<typeof vi.fn>
let disposeLocales: () => void = () => undefined
let queryClient: QueryClient

beforeEach(() => {
  rest = vi.fn()
  bindAmbitionApi(rest as unknown as AmbitionRest)
  disposeLocales = registerPluginLocales('ambition', AMBITION_LOCALES)
  queryClient = new QueryClient({ defaultOptions: { queries: { retry: false } } })
  $selectedStoredSessionId.set(SESSION)
})

afterEach(() => {
  cleanup()
  disposeLocales()
  $selectedStoredSessionId.set(null)
  queryClient.clear()
})

const slot = (container: HTMLElement, name: string): HTMLElement | null =>
  container.querySelector(`[data-slot="${name}"]`)

/** The summary read happened (the api layer passes an explicit `undefined`
 *  for absent options, so match on the path alone). */
const readSummary = () => rest.mock.calls.some(call => call[0] === `/sessions/${SESSION}`)

interface JudgeProps {
  args?: Record<string, unknown>
  isError?: boolean
  result?: unknown
}

/**
 * Mount the chip with the session's card carrying `currentTarget` (null = the
 * summary does not carry it; `unreadable` = the backend refuses the read, as it
 * does without the ambition plugin).
 */
const mount = (
  props: JudgeProps = {},
  currentTarget: null | string = JUDGED_TARGET,
  unreadable = false
) => {
  rest.mockImplementation((path: string) => {
    if (path !== `/sessions/${SESSION}`) {
      return Promise.resolve({})
    }

    if (unreadable) {
      return Promise.reject(new Error('404: {"detail":"No such API endpoint: /api/plugins/ambition"}'))
    }

    return Promise.resolve({ cards: currentTarget === null ? [] : [card(currentTarget)], enabled: true })
  })

  return render(
    <QueryClientProvider client={queryClient}>
      <AmbitionJudgePart
        args={props.args ?? args()}
        isError={props.isError ?? false}
        result={props.result ?? result}
        toolCallId="tc-2"
        toolName="ambition_judge"
      />
    </QueryClientProvider>
  )
}

describe('AmbitionJudgePart', () => {
  it('renders target vs measured as numbers with the verdict mark', async () => {
    const { container } = mount()

    expect(slot(container, 'ambition-judge')?.getAttribute('data-verdict')).toBe('pass')
    expect(slot(container, 'ambition-judge-target')?.textContent).toBe('Target: 12 notes')
    expect(slot(container, 'ambition-judge-measured')?.textContent).toBe('Measured: 12 notes')
    expect(screen.getByLabelText('Pass')).toBeTruthy()
    expect(container.textContent).toContain('outside checklist tool')
  })

  it('maps fail to the error mark and inconclusive to the muted one', () => {
    const failing = mount({ args: args({ verdict: 'fail' }), result: { ...result, verdict: 'fail' } })

    expect(slot(failing.container, 'ambition-judge')?.getAttribute('data-verdict')).toBe('fail')
    expect(screen.getByLabelText('Fail')).toBeTruthy()

    cleanup()

    const unclear = mount({
      args: args({ measured: 'no reading', verdict: 'inconclusive' }),
      result: { ...result, verdict: 'inconclusive' }
    })

    expect(slot(unclear.container, 'ambition-judge')?.getAttribute('data-verdict')).toBe('inconclusive')
    expect(screen.getByLabelText('Inconclusive')).toBeTruthy()
  })

  it('expands the evidence on click and hides it again', async () => {
    const { container } = mount()

    expect(slot(container, 'ambition-judge-evidence')).toBeNull()

    fireEvent.click(slot(container, 'ambition-judge-evidence-toggle') as HTMLElement)

    await waitFor(() =>
      expect(slot(container, 'ambition-judge-evidence')?.textContent).toContain('12 of 12 notes generated')
    )

    fireEvent.click(slot(container, 'ambition-judge-evidence-toggle') as HTMLElement)

    await waitFor(() => expect(slot(container, 'ambition-judge-evidence')).toBeNull())
  })

  it('keeps the judged target and flags it when the card moved after the verdict', async () => {
    const { container } = mount({}, '30 notes')

    // The verdict was measured against 12 notes; the card now claims 30.
    expect(slot(container, 'ambition-judge-target')?.textContent).toBe('Target: 12 notes')

    await waitFor(() =>
      expect(slot(container, 'ambition-judge-target-edited')?.textContent).toBe(
        'target edited after judging: 30 notes'
      )
    )
  })

  it('stays quiet when the card still carries the target the judge was handed', async () => {
    const { container } = mount({}, JUDGED_TARGET)

    await waitFor(() => expect(readSummary()).toBe(true))
    expect(slot(container, 'ambition-judge-target')?.textContent).toBe('Target: 12 notes')
    expect(slot(container, 'ambition-judge-target-edited')).toBeNull()
  })

  it('renders the judged target alone when the card cannot be read', async () => {
    const { container } = mount({}, JUDGED_TARGET, true)

    await waitFor(() => expect(readSummary()).toBe(true))
    expect(slot(container, 'ambition-judge-target')?.textContent).toBe('Target: 12 notes')
    expect(slot(container, 'ambition-judge-target-edited')).toBeNull()
  })

  it('renders the judged target with no read on a chat that has no stored session', () => {
    $selectedStoredSessionId.set(null)

    const { container } = mount()

    expect(slot(container, 'ambition-judge-target')?.textContent).toBe('Target: 12 notes')
    expect(slot(container, 'ambition-judge-target-edited')).toBeNull()
    expect(rest.mock.calls.length).toBe(0)
  })

  it('renders the honest error line when the plugin rejected the record', () => {
    const { container } = mount({
      result: { error: 'the judge must be OUTSIDE this run', ok: false, reason: 'self_judge' }
    })

    expect(slot(container, 'ambition-judge-error')).toBeTruthy()
    expect(container.textContent).toContain('the judge must be OUTSIDE this run')
    expect(slot(container, 'ambition-judge')).toBeNull()
  })
})
